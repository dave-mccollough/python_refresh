# Python Operators

# Arthmetic Operators

a = 10
b = 3

# Addition
print(a + b) # 13
# Subtraction
print(a - b) # 10
# Multiplication
print(a * b) # 30
# Division
print(a / b) # 3.3333333333333335
# Exponent
print(a ** b) # 1000
# Modulo
print(a % b) # 1


# Assignment Operators

# Equals
x = 10
print(x) # 10

# Plus and equals
y = 5
y += 5
print(y) # 10

# Multiply and equals
a = 5
a *= 6
print(a) # 30

# Comparison Operators

b = 7
c = 5

print(b == c) # False
print(b != c) # True
print(b > c)  # True
print(b < c) # False
print(b >= c) # True
print(b <= c) # False

# Logical Operators

d = 10
e = 13

print((e > d) and (d < e)) # True
print((e < d) or (e > d)) # True

